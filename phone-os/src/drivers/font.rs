/// Font renderer for drawing text on framebuffer
pub struct FontRenderer {
    font_data: &'static [[u8; 16]; 96],
    char_width: usize,
    char_height: usize,
}

impl FontRenderer {
    /// Create a new font renderer
    pub const fn new() -> Self {
        FontRenderer {
            font_data: &FONT_8X16,
            char_width: 8,
            char_height: 16,
        }
    }

    /// Get character width
    pub const fn char_width(&self) -> usize {
        self.char_width
    }

    /// Get character height
    pub const fn char_height(&self) -> usize {
        self.char_height
    }

    /// Draw a character at specified position
    /// 
    /// # Arguments
    /// * `fb` - Framebuffer writer
    /// * `c` - Character to draw
    /// * `x` - X position in pixels
    /// * `y` - Y position in pixels
    /// * `fg` - Foreground color
    /// * `bg` - Background color
    pub fn draw_char(
        &self,
        fb: &mut FramebufferWriter,
        c: char,
        x: usize,
        y: usize,
        fg: Color,
        bg: Color,
    ) {
        let char_code = if c >= ' ' && c <= '~' {
            (c as usize) - (' ' as usize)
        } else {
            0 // Use space for unknown characters
        };

        let glyph = &self.font_data[char_code];

        unsafe {
            for row in 0..self.char_height {
                let byte = glyph[row];
                for col in 0..self.char_width {
                    let bit_mask = 0x80 >> col;
                    let pixel_on = (byte & bit_mask) != 0;
                    let color = if pixel_on { fg } else { bg };
                    
                    // Use the framebuffer's internal draw_pixel through unsafe access
                    // This is a simplified approach - in production, expose draw_pixel publicly
                    self.draw_pixel_at(fb, x + col, y + row, color);
                }
            }
        }
    }

    /// Draw a string at specified position
    pub fn draw_string(
        &self,
        fb: &mut FramebufferWriter,
        s: &str,
        x: usize,
        y: usize,
        fg: Color,
        bg: Color,
    ) -> usize {
        let mut current_x = x;
        for c in s.chars() {
            if c == '\n' {
                break; // Handle newlines externally
            } else if c != '\r' && c != '\t' {
                self.draw_char(fb, c, current_x, y, fg, bg);
                current_x += self.char_width;
            }
        }
        current_x - x
    }

    /// Measure string width in pixels
    pub fn measure_string(&self, s: &str) -> usize {
        let mut width = 0;
        for c in s.chars() {
            if c != '\n' && c != '\r' && c != '\t' {
                width += self.char_width;
            }
        }
        width
    }

    /// Internal pixel drawing helper
    unsafe fn draw_pixel_at(&self, fb: &mut FramebufferWriter, x: usize, y: usize, color: Color) {
        // Access framebuffer info through public interface
        // This is a placeholder - actual implementation would need direct framebuffer access
        use core::ptr;
        
        // Get framebuffer address from the writer (would need public accessor in production)
        let fb_addr = 0xE0000000u64; // Placeholder - should get from FramebufferInfo
        let width = 1080usize; // Placeholder
        let stride = width * 4;
        
        if x >= width || y >= 1920 {
            return;
        }
        
        let fb_ptr = fb_addr as *mut u32;
        let offset = y * stride / 4 + x;
        ptr::write_volatile(fb_ptr.add(offset), color.as_u32());
    }
}

impl Default for FontRenderer {
    fn default() -> Self {
        Self::new()
    }
}

/// Text alignment options
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum TextAlign {
    Left,
    Center,
    Right,
}

/// Text layout engine for positioning text
pub struct TextLayout {
    pub x: usize,
    pub y: usize,
    pub width: usize,
    pub height: usize,
    pub align: TextAlign,
    pub line_height: usize,
}

impl TextLayout {
    pub const fn new(x: usize, y: usize, width: usize, height: usize) -> Self {
        TextLayout {
            x,
            y,
            width,
            height,
            align: TextAlign::Left,
            line_height: 16,
        }
    }

    pub fn set_align(&mut self, align: TextAlign) {
        self.align = align;
    }

    pub fn set_line_height(&mut self, height: usize) {
        self.line_height = height;
    }

    /// Calculate position for a line of text based on alignment
    pub fn calculate_line_position(&self, line_width: usize, line_num: usize) -> (usize, usize) {
        let x = match self.align {
            TextAlign::Left => self.x,
            TextAlign::Center => self.x + (self.width - line_width) / 2,
            TextAlign::Right => self.x + self.width - line_width,
        };
        let y = self.y + line_num * self.line_height;
        (x, y)
    }
}
