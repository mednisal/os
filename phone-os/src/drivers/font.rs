/// Maximum supported font size
const MAX_FONT_SIZE: usize = 72;

/// Glyph metrics
#[derive(Debug, Clone, Copy)]
pub struct GlyphMetrics {
    pub width: u8,
    pub height: u8,
    pub bearing_x: i8,
    pub bearing_y: i8,
    pub advance: u8,
}

/// Rendered glyph bitmap
#[derive(Debug, Clone)]
pub struct GlyphBitmap {
    pub metrics: GlyphMetrics,
    // Note: Vec requires allocator, use fixed array in no_std
    pub pixel_count: usize,
}

/// Font face information
#[derive(Debug, Clone)]
pub struct FontFace {
    pub name: &'static str,
    pub size: u8,
    pub is_bold: bool,
    pub is_italic: bool,
}

